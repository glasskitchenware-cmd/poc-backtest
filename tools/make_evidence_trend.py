#!/usr/bin/env python3
"""Builds web/evidence_trend.js from the research workflow's own output, never retyped:
research/pro/evidence_trend_<date>.json (pro.js: walk-forward evidence, normal range, stop rules) and
research/pro/robust_<date>.json (robust.js: unseen coins, 2017-2019, yearly outcomes, open-position cap), both copied
from the branch research-results that the research jobs push.
Usage: python3 tools/make_evidence_trend.py EVIDENCE_JSON ROBUST_JSON "PRO_RUN_INFO" "ROBUST_RUN_INFO" """
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
evidence_path, robust_path, pro_run, robust_run = sys.argv[1:5]
ev = json.loads(Path(evidence_path).read_text(encoding="utf-8"))
robust = json.loads(Path(robust_path).read_text(encoding="utf-8"))
for key in ("all", "ladder", "normal", "stopRules", "parity", "replay"):
    if key not in ev:
        sys.exit(f"{evidence_path}: missing '{key}'")
for key in ("unseen", "spot", "yearly", "base", "heat"):
    if key not in robust:
        sys.exit(f"{robust_path}: missing '{key}'")
ev["robust"] = robust
ev["source"] = "Binance USD-M futures 4h klines 2020-01..2026-09 and spot 4h 2017-08..2019-12 (data.binance.vision), research/pro/pro.js and robust.js"
header = f"""/* Generated by tools/make_evidence_trend.py from {Path(evidence_path).as_posix().split('poc-backtest/')[-1]} ({pro_run}) and
 * {Path(robust_path).as_posix().split('poc-backtest/')[-1]} ({robust_run}): the research jobs' own JSON from branch
 * research-results, not retyped. Trend 4H (web/trend.js) in the years the walk-forward chose it (2023-01..2026-09) with the
 * app's leverage filter; reach rates; the scale-out plan chosen on 2020-2022; late entry; what is normal (streaks, ranges of
 * N trades, drawdowns); stop rules; robustness on 25 unseen coins and on 2017-2019; how often a year ends in a loss. */
"""
out = ROOT / "web" / "evidence_trend.js"
out.write_text(header + "window.EVIDENCE_TREND = " + json.dumps(ev, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
print("wrote", out, out.stat().st_size, "bytes")
